#!/usr/bin/env python3
"""Build one FDE stage-2 contact round and a generated project summary."""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
from datetime import date
from pathlib import Path
from urllib.parse import urlparse

MARKER = "<!-- Generated by fde-contact-form; edit the JSON record through the Skill. -->"
ID = re.compile(r"^[A-Za-z0-9_-]+$")


def need(obj: dict, key: str, where: str) -> str:
    value = obj.get(key)
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{where}.{key} 必须是非空文本")
    return value.strip()


def rows(obj: dict, key: str, where: str) -> list[dict]:
    value = obj.get(key)
    if not isinstance(value, list) or any(not isinstance(x, dict) for x in value):
        raise ValueError(f"{where}.{key} 必须是对象列表")
    return value


def unique_ids(items: list[dict], where: str) -> None:
    ids = [need(item, "id", where) for item in items]
    if len(ids) != len(set(ids)):
        raise ValueError(f"{where} 内编号重复")
    if any(not ID.fullmatch(value) for value in ids):
        raise ValueError(f"{where} 编号只能含英文、数字、下划线和连字符")


def check(payload: dict, root: Path) -> None:
    if not isinstance(payload, dict):
        raise ValueError("输入必须是 JSON 对象")
    project = payload.get("project")
    rd = payload.get("round")
    if not isinstance(project, dict) or not isinstance(rd, dict):
        raise ValueError("需要 project 和 round 对象")
    for key in ("id", "name", "client"):
        need(project, key, "project")
    rid = need(rd, "id", "round")
    if not ID.fullmatch(rid):
        raise ValueError("round.id 只能含英文、数字、下划线和连字符")
    try:
        date.fromisoformat(need(rd, "date", "round"))
    except ValueError as exc:
        raise ValueError("round.date 应为 YYYY-MM-DD") from exc
    for key in ("topic", "decisionMaker", "businessOwner", "operator", "itContact", "businessGoal", "asIs", "pain", "desiredOutcome", "scenario", "conclusion", "nextActions", "acceptanceDraft"):
        need(rd, key, "round")
    participants = rd.get("participants")
    if not isinstance(participants, list) or not participants or any(not isinstance(p, str) or not p.strip() for p in participants):
        raise ValueError("round.participants 需要非空姓名列表")
    people = rows(payload, "organization", "input")
    for person in people:
        for key in ("name", "title", "projectRole", "concern", "contact"):
            need(person, key, "organization")
        if not isinstance(person.get("decisionMaker"), bool):
            raise ValueError("organization.decisionMaker 必须是布尔值")
    if len({p["name"] for p in people}) != len(people):
        raise ValueError("organization 人名重复")
    for key, fields in {
        "requirements": ("description", "priority"),
        "processNodes": ("name", "role", "input", "action", "output", "system", "exception", "aiInsertion"),
        "dataItems": ("name", "sourceSystem", "content", "method", "availability", "frequency", "owner", "readinessAiImpact"),
    }.items():
        items = rows(rd, key, "round")
        unique_ids(items, f"round.{key}")
        for item in items:
            for field in fields:
                need(item, field, f"round.{key}")
            if key == "requirements" and any(not isinstance(item.get(field), bool) for field in ("inScope", "involvesAi")):
                raise ValueError("需求的 inScope 和 involvesAi 必须是布尔值")
    for item in rows(rd, "acceptanceMetrics", "round"):
        for key in ("name", "target", "judge", "aiCriterion"):
            need(item, key, "acceptanceMetrics")
    for item in rows(rd, "openItems", "round"):
        for key in ("item", "owner"):
            need(item, key, "openItems")
        if item.get("status") != "pending":
            raise ValueError("openItems.status 必须是 pending；已解决项应移出待确认清单")
    confirmation = rd.get("confirmation")
    if not isinstance(confirmation, dict) or confirmation.get("status") not in ("pending", "confirmed"):
        raise ValueError("confirmation.status 必须是 pending 或 confirmed")
    if confirmation["status"] == "confirmed":
        try:
            date.fromisoformat(need(confirmation, "date", "confirmation"))
        except ValueError as exc:
            raise ValueError("confirmation.date 应为 YYYY-MM-DD") from exc
        evidence = need(confirmation, "evidence", "confirmation")
        parsed = urlparse(evidence)
        if parsed.scheme not in ("", "http", "https"):
            raise ValueError("确认凭据须为项目内相对路径或 http(s) 链接")
        if not parsed.scheme:
            path = (root / evidence).resolve()
            if not path.is_relative_to(root.resolve()) or not path.is_file():
                raise ValueError("项目内确认凭据文件不存在或路径越界")


def cell(value: object) -> str:
    return str(value if value is not None else "").replace("|", "\\|").replace("\n", "<br>")


def table(headers: list[str], data: list[list[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in data]
    return "\n".join(lines)


def yes(value: bool) -> str:
    return "是" if value else "否"


def blank_template_value(value: object) -> bool:
    if isinstance(value, dict):
        return all(blank_template_value(v) for v in value.values())
    if isinstance(value, list):
        return all(blank_template_value(v) for v in value)
    return value == "" or isinstance(value, (bool, int))


def render(project: dict, people: list[dict], rd: dict) -> str:
    reqs, nodes, data, conf = rd["requirements"], rd["processNodes"], rd["dataItems"], rd["confirmation"]
    pending = "；".join(f"{x['item']}（{x['owner']}，待确认）" for x in rd["openItems"]) or "本轮未登记未定事项"
    ai_conclusion = rd.get("aiCapabilityConclusion") or "待确认（FDE与业务方核对本轮AI能力范围）"
    ai_value = rd.get("aiValue") or "待确认（FDE与业务方核对AI介入价值，不预设提升数值）"
    parts = [
        f"# 需求与数据对接确认表（含组织关系）— {rd['id']}",
        "## 一、基本信息", table(["项目", "内容"], [["项目名称",project['name']],["客户/单位",project['client']],["本次议题",rd['topic']],["沟通日期",rd['date']],["参会人员",'、'.join(rd['participants'])],["所属沟通轮次",rd['id']]]),
        "## 二、组织关系", "### 2.1 关键人清单", table(["姓名","职务","项目角色","关注点"], [[p['name'],p['title'],p['projectRole'],p['concern']] for p in people]),
        "联系与确认方式：" + "；".join(f"{p['name']}：{p['contact']}（是否决策人：{yes(p['decisionMaker'])}）" for p in people),
        "## 三、本次结论与确认", table(["项目","内容"],[["本次达成结论",rd['conclusion']],["遗留未定事项",pending],["下一步行动计划",rd['nextActions']],["AI能力确认结论",ai_conclusion]]),
        "## 四、业务场景", "### 4.1 场景概述", table(["项目","内容"],[["业务目标",rd['businessGoal']],["现状基线（As-Is）",rd['asIs']],["业务痛点",rd['pain']],["期望效果（To-Be）",rd['desiredOutcome']],["AI介入价值",ai_value]]),
        "场景：" + rd['scenario'], "### 4.2 业务流程", " → ".join(x['name'] for x in nodes) or "待确认（业务方提供流程）",
        "### 4.3 需求清单", table(["序号","需求描述","优先级","本期是否实施","备注（来源/约束）","是否涉及AI"],[[x['id'],x['description'],x['priority'],yes(x['inScope']),f"来源轮次：{rd['id']}；{x.get('constraint') or '未登记额外约束'}",yes(x['involvesAi'])] for x in reqs]),
        "### 4.4 业务流程", table(["步骤","节点/环节","执行角色","输入","处理动作","输出","涉及系统","异常/例外处理","AI嵌入"],[[x['id'],x['name'],x['role'],x['input'],x['action'],x['output'],x['system'],x['exception'],x['aiInsertion']] for x in nodes]),
        "### 4.5 数据对接", table(["序号","数据项","源系统/厂商","数据内容","对接方式","可否提供","更新频率","责任人","就绪度AI影响"],[[x['id'],x['name'],x['sourceSystem']+(' / '+x['vendor'] if x.get('vendor') else ''),x['content'],x['method'],x['availability'],x['frequency'],x['owner'],x['readinessAiImpact']] for x in data]),
        "### 4.6 验收标准初稿", rd['acceptanceDraft'], table(["验收指标","目标值","验收方","AI专项验收口径"],[[x['name'],x['target'],x['judge'],x['aiCriterion']] for x in rd['acceptanceMetrics']]),
        "## 五、当轮确认（补充记录）",f"状态：{conf['status']}；时间：{conf.get('date') or '未确认'}；凭据：{conf.get('evidence') or '未提供'}",
        "> 本表为阶段二逐轮沟通记录。知识中心原表结构保留，确认凭据为补充记录；阶段三另做最终需求确认。",
    ]
    return "\n\n".join(parts) + "\n"


def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent, delete=False) as file:
        tmp = Path(file.name)
        file.write(content)
    os.replace(tmp, path)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("project_dir", type=Path)
    ap.add_argument("--input", required=True, type=Path)
    ap.add_argument("--replace-round", action="store_true")
    ap.add_argument("--migrate-existing", action="store_true", help="保留旧稿备份后，将已人工核对的JSON按知识中心结构重整")
    args = ap.parse_args()
    root = args.project_dir.resolve()
    if not root.is_dir():
        raise ValueError("项目目录不存在")
    payload = json.loads(args.input.read_text(encoding="utf-8"))
    check(payload, root)
    project, incoming, rd = payload["project"], payload["organization"], payload["round"]
    record_path = root / "project-record.json"
    record = json.loads(record_path.read_text(encoding="utf-8")) if record_path.exists() else {"schemaVersion": "0.1", "project": project, "stage2": {}}
    if not isinstance(record, dict) or not isinstance(record.get("stage2"), dict):
        raise ValueError("现有 project-record.json 结构不兼容")
    old_project = record.get("project", {})
    if any(old_project.get(k) not in (None, "", project[k]) for k in ("id", "name", "client")):
        raise ValueError("项目基本信息与现有记录冲突")
    record["project"] = {**old_project, **project}
    contact = record["stage2"].setdefault("contactForm", {"document": "stage2/contact-form.md", "rounds": []})
    if not isinstance(contact, dict) or contact.get("document") != "stage2/contact-form.md" or not isinstance(contact.get("rounds"), list):
        raise ValueError("现有 contactForm 结构不兼容")
    existing_people = contact.get("organization", [])
    if not isinstance(existing_people, list):
        raise ValueError("现有组织关系结构不兼容")
    by_name = {p["name"]: p for p in existing_people}
    for person in incoming:
        prior = by_name.get(person["name"])
        if prior and prior != person and not args.replace_round:
            raise ValueError(f"组织关系与现有记录冲突：{person['name']}；核对后使用 --replace-round")
        by_name[person["name"]] = person
    people = list(by_name.values())
    rounds = contact["rounds"]
    if len(rounds) == 1 and isinstance(rounds[0], dict) and blank_template_value(rounds[0]):
        rounds = []  # The standards kit's untouched placeholder round.
    prior_ids = [x.get("id") for x in rounds]
    if len(prior_ids) != len(set(prior_ids)):
        raise ValueError("现有轮次编号重复")
    old_index = next((i for i, x in enumerate(rounds) if x.get("id") == rd["id"]), None)
    if old_index is not None and not args.replace_round:
        raise ValueError("轮次已存在；核对后使用 --replace-round 修订")
    round_path = root / "stage2" / "contact-rounds" / f"{rd['id']}.md"
    summary_path = root / "stage2" / "contact-form.md"
    blank_form = (Path(__file__).resolve().parent.parent / "assets" / "blank-contact-form.md").read_text(encoding="utf-8")
    for path in (round_path, summary_path):
        if path.exists() and not (path.read_text(encoding="utf-8").startswith(MARKER) or (path == summary_path and path.read_text(encoding="utf-8") == blank_form)):
            if not args.migrate_existing:
                raise ValueError(f"拒绝覆盖非本工具生成的文件：{path}；读回旧稿核对后，使用 --migrate-existing 保留备份再重整")
            import hashlib
            backup = root / '.fde-flow' / 'format-history' / (hashlib.sha256(path.read_bytes()).hexdigest()[:16] + '-' + path.name)
            if not backup.exists():
                atomic_write(backup, path.read_text(encoding='utf-8'))
    if round_path.exists() and old_index is None:
        raise ValueError("轮次文件已存在但记录中没有该轮；请人工核对")
    updated = [*rounds]
    if old_index is None:
        updated.append(rd)
    else:
        updated[old_index] = rd
    docs = []
    for item in updated:
        if item["id"] == rd["id"]:
            docs.append(render(project, people, rd))
        else:
            old_path = root / "stage2" / "contact-rounds" / f"{item['id']}.md"
            if not old_path.is_file():
                raise ValueError(f"缺少历史轮次文件：{item['id']}")
            old = old_path.read_text(encoding="utf-8")
            if not old.startswith(MARKER):
                raise ValueError(f"历史轮次文件非本工具生成：{item['id']}")
            docs.append(old[len(MARKER):].strip() + "\n")
    contact["organization"] = people
    contact["rounds"] = updated
    summary = MARKER + "\n\n" + "\n\n---\n\n".join(docs)
    atomic_write(round_path, MARKER + "\n\n" + render(project, people, rd))
    atomic_write(summary_path, summary)
    atomic_write(record_path, json.dumps(record, ensure_ascii=False, indent=2) + "\n")
    print(f"已写入 {round_path.relative_to(root)}、{summary_path.relative_to(root)}、project-record.json")
    print(f"轮次 {rd['id']}：{'已确认（凭据仍须人工核对）' if rd['confirmation']['status'] == 'confirmed' else '待客户当轮确认'}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError, json.JSONDecodeError) as exc:
        print(f"错误：{exc}", file=sys.stderr)
        sys.exit(2)
